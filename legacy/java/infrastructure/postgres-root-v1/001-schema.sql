CREATE TABLE accounts (
 id uuid PRIMARY KEY, email varchar(255) UNIQUE NOT NULL, name varchar(255) NOT NULL,
 password varchar(255) NOT NULL, role varchar(255) NOT NULL,
 balance numeric(19,2) NOT NULL CHECK(balance>=0)
);
CREATE TABLE matches (
 id uuid PRIMARY KEY, home varchar(255) NOT NULL, away varchar(255) NOT NULL,
 created_at timestamptz NOT NULL, closes_at timestamptz NOT NULL,
 status varchar(255) NOT NULL CHECK(status IN ('OPEN_FOR_BETS','CLOSED','FINISHED')),
 winner varchar(255) CHECK(winner IN ('HOME','AWAY')), finish_requested boolean NOT NULL DEFAULT false
);
CREATE TABLE bets (
 id uuid PRIMARY KEY, match_id uuid NOT NULL REFERENCES matches(id), user_id uuid NOT NULL REFERENCES accounts(id),
 selection varchar(255) NOT NULL CHECK(selection IN ('HOME','AWAY')), stake numeric(19,2) NOT NULL CHECK(stake>0),
 placed_at timestamptz NOT NULL, status varchar(255) NOT NULL,
 request_id uuid UNIQUE NOT NULL
);
CREATE INDEX bets_match_idx ON bets(match_id);
CREATE INDEX bets_user_idx ON bets(user_id,placed_at DESC);
CREATE TABLE settlements (
 bet_id uuid PRIMARY KEY REFERENCES bets(id), user_id uuid NOT NULL REFERENCES accounts(id),
 outcome varchar(255) NOT NULL, payout numeric(19,2) NOT NULL CHECK(payout>=0), settled_at timestamptz NOT NULL
);
CREATE TABLE ledger (
 id uuid PRIMARY KEY, user_id uuid NOT NULL REFERENCES accounts(id), bet_id uuid NOT NULL REFERENCES bets(id),
 amount numeric(19,2) NOT NULL, reason varchar(255) NOT NULL, created_at timestamptz NOT NULL,
 UNIQUE(bet_id,reason)
);
CREATE TABLE event_journal (
 id uuid PRIMARY KEY, match_id uuid NOT NULL REFERENCES matches(id), event_offset bigint NOT NULL, payload text NOT NULL,
 UNIQUE(match_id,event_offset)
);
CREATE INDEX event_match_idx ON event_journal(match_id,event_offset);
CREATE TABLE outbox (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, owner varchar(255) NOT NULL,
 match_id uuid NOT NULL, destination varchar(255) NOT NULL, routing_key varchar(255) NOT NULL,
 payload text NOT NULL, due_at timestamptz, sent boolean NOT NULL DEFAULT false
);
CREATE INDEX outbox_pending_idx ON outbox(owner,id) WHERE NOT sent;
CREATE TABLE audit (id uuid PRIMARY KEY, action varchar(255) NOT NULL, detail text NOT NULL, created_at timestamptz NOT NULL);
CREATE TABLE delivered_notifications (id varchar(255) PRIMARY KEY, delivered_at timestamptz NOT NULL);
